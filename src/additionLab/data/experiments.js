export const PLAYABLE_EXPERIMENTS = EXPERIMENTS.filter((experiment) => isExperimentPlayable(experiment));

export function isExperimentPlayable(experiment) {
  const entry = typeof experiment === 'string' ? getExperiment(experiment) : experiment;
  if (!entry) return false;
  return entry.playable !== false && entry.review.status !== 'draft';
}

export function getExperiment(id) {
  return EXPERIMENTS.find((experiment) => experiment.id === id) ?? null;
}

export function getExperimentIndex(id) {
  return EXPERIMENTS.findIndex((experiment) => experiment.id === id);
}

export function getExperimentsByZone(zoneId) {
  return EXPERIMENTS.filter((experiment) => experiment.zone === zoneId);
}

export function countPlayableExperiments() {
  return EXPERIMENTS.filter((experiment) => isExperimentPlayable(experiment)).length;
}
